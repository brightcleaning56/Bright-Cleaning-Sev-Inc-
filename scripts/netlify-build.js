'use strict';

// Netlify build step: writes public/config.js so the static console calls the API host.
// Fails the build if the API address is missing or is not HTTPS, so a console can never
// be published pointing at nothing or at an unencrypted address.
const fs = require('fs');
const path = require('path');

const raw = String(process.env.BUILDINTEL_API_URL || '').trim().replace(/\/+$/, '');
if (!/^https:\/\/[^\s/]+$/.test(raw)) {
  console.error('BUILDINTEL_API_URL must be set to the API origin, for example https://buildintel-api.onrender.com');
  process.exit(1);
}
const out = path.resolve(__dirname, '..', 'public', 'config.js');
fs.writeFileSync(out, `// Generated by scripts/netlify-build.js. Do not edit.\nwindow.BUILDINTEL_API = ${JSON.stringify(raw)};\n`);
console.log(`console configured for API at ${raw}`);
