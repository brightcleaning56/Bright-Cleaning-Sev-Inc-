// Prepares the settings for one new company copy (pilot stage: one copy per company).
// It makes no calls to any hosting, phone, email or payment provider. It writes files only.
//
//   node scripts/new-company-copy.js --name "Acme Cleaning" --slug acme-cleaning \
//     --domain acmeclean.com --admin-email owner@acmeclean.com --tz America/Chicago --out ../copies
//
// Output (in <out>/<slug>/):
//   env.txt        settings to paste into the new copy's hosting environment (secrets left blank are marked)
//   CHECKLIST.md   the onboarding steps from the business plan, with the owner's steps first
// Existing output folders are never overwritten.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

function arg(name) {
  const i = process.argv.indexOf('--' + name);
  return i > -1 && process.argv[i + 1] ? String(process.argv[i + 1]).trim() : '';
}

function fail(msg) {
  console.error('Error: ' + msg);
  console.error('Usage: node scripts/new-company-copy.js --name "Company" --slug company-slug --domain company.com --admin-email owner@company.com [--tz America/Chicago] [--out ../copies]');
  process.exit(1);
}

const name = arg('name');
const slug = arg('slug');
const domain = arg('domain').toLowerCase();
const adminEmail = arg('admin-email').toLowerCase();
const tz = arg('tz') || 'America/Chicago';
const outRoot = arg('out') || path.join('..', 'company-copies');

if (!name) fail('--name is required.');
if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(slug) || slug.length > 40) fail('--slug must be lowercase letters, digits and hyphens (max 40 characters).');
if (!/^[a-z0-9-]+(\.[a-z0-9-]+)+$/.test(domain)) fail('--domain must be a domain such as company.com.');
if (!/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(adminEmail)) fail('--admin-email must be a valid email address.');
try { new Intl.DateTimeFormat('en-US', { timeZone: tz }); } catch (e) { fail('--tz is not a valid time zone name.'); }

const dir = path.resolve(outRoot, slug);
if (fs.existsSync(dir)) fail('Output folder already exists: ' + dir + ' (nothing was changed).');
fs.mkdirSync(dir, { recursive: true });

const jwt = crypto.randomBytes(48).toString('hex');
const lines = [
  '# Settings for the ' + name + ' copy. Paste into the hosting provider\'s environment settings.',
  '# Lines marked SET-IN-PROVIDER are secrets or account IDs the owner creates; they are never written here.',
  '',
  'NODE_ENV=production',
  'NODE_VERSION=22',
  'TRUST_PROXY=1',
  'JWT_SECRET=' + jwt,
  'ADMIN_EMAIL=' + adminEmail,
  'ADMIN_PASSWORD_HASH=SET-IN-PROVIDER (run: node scripts/create-admin.js ' + adminEmail + ' "password")',
  'PUBLIC_BASE_URL=https://' + domain,
  'FROM_EMAIL=info@' + domain,
  'NOTIFY_EMAIL=info@' + domain,
  'BUSINESS_TZ=' + tz,
  'DATA_DIR=/opt/render/project/src/persist/data',
  'UPLOAD_DIR=/opt/render/project/src/persist/uploads',
  'SMTP_HOST=smtp.office365.com',
  'SMTP_PORT=587',
  'SMTP_SECURE=false',
  'SMTP_USER=info@' + domain,
  'SMTP_PASS=SET-IN-PROVIDER',
  'POSTMARK_TOKEN=SET-IN-PROVIDER (optional, if Postmark is used)',
  'STRIPE_SECRET_KEY=SET-IN-PROVIDER',
  'STRIPE_WEBHOOK_SECRET=SET-IN-PROVIDER',
  'ANTHROPIC_API_KEY=SET-IN-PROVIDER',
  'TWILIO_ACCOUNT_SID=SET-IN-PROVIDER',
  'TWILIO_AUTH_TOKEN=SET-IN-PROVIDER',
  'TWILIO_NUMBER=SET-IN-PROVIDER',
  'TWILIO_FORWARD_TO=SET-IN-PROVIDER',
  'BACKUP_BUCKET=SET-IN-PROVIDER',
  'BACKUP_KEY_ID=SET-IN-PROVIDER',
  'BACKUP_KEY_SECRET=SET-IN-PROVIDER',
  'BACKUP_KEY=SET-IN-PROVIDER (encryption key; store it in the password manager too)',
  ''
];
fs.writeFileSync(path.join(dir, 'env.txt'), lines.join('\n'), { flag: 'wx' });

const checklist = `# New copy: ${name}

Target: one day once the setup script exists. Business plan, Operations and support.

## Owner steps (not automated)
1. Create the email domain ${domain}, the Stripe account, the phone number and the hosting service.
2. Put the SET-IN-PROVIDER values from env.txt into the hosting environment. Never paste them into chat.
3. Set the admin password: node scripts/create-admin.js ${adminEmail} "<14+ characters>" and copy the printed hash.

## Setup steps
4. Deploy the copy from the repository and wait for /api/health to show the expected build.
5. Import customers, pricebook, staff and crew.
6. Turn on two-step sign-in for owners and managers.
7. Train the owner and office in one session. Set the AI receptionist greeting and the recording notice.
8. Run a test call, a test estimate and a test invoice.
9. Confirm the first encrypted backup has run.

Time zone: ${tz}. Generated by scripts/new-company-copy.js. Do not commit this folder.
`;
fs.writeFileSync(path.join(dir, 'CHECKLIST.md'), checklist, { flag: 'wx' });

console.log('Created ' + dir);
console.log('  env.txt       settings to paste; secrets are marked SET-IN-PROVIDER');
console.log('  CHECKLIST.md  owner steps first, then setup steps');
console.log('Nothing was sent to any provider. Keep this folder out of the repository.');
