import './_env.js';
import test from 'node:test';
import assert from 'node:assert/strict';
import { Store } from '../src/store.js';
import { publisherPortfolio, createPublication, addPackage, decideVerification } from '../src/publishing.js';

test('the portfolio lists every project of one company with its packages, bids and attention flags', () => {
  const store = new Store(null);
  const gc = store.put('orgs', { slug: 'gc', name: 'ABC Development Group', kind: 'buyer', buyerKind: 'developer', status: 'active', settings: {} });
  const other = store.put('orgs', { slug: 'other', name: 'Other', kind: 'buyer', buyerKind: 'developer', status: 'active', settings: {} });
  const owner = store.put('users', { email: 'gm@abc.test', role: 'owner', orgId: gc.id });
  decideVerification(store, { email: 'staff' }, gc.id, { status: 'verified', note: 'checked' });
  const D = d => new Date(Date.now() + d * 864e5).toISOString().slice(0, 10);
  const PROJECT = { title: 'Clinic', address: '1200 SE Delaware Ave', city: 'Ankeny', state: 'IA', projectType: 'medical', description: 'New 120,000 SF medical office building', estValue: 48500000 };
  const clinic = createPublication(store, gc, owner, PROJECT).publication;
  const draft = createPublication(store, gc, owner, { ...PROJECT, title: 'Warehouse', city: 'Des Moines' }).publication;
  const pkg = (pubId, title, dueDate) => addPackage(store, gc, owner, pubId, { title, trades: ['electrical'], dueDate, projectType: 'medical', description: 'Electrical: complete scope per drawings and specifications', noDocuments: true }).package;
  const elec = pkg(clinic.id, 'Electrical', D(5));
  const late = pkg(clinic.id, 'Plumbing', D(5));
  const done = pkg(clinic.id, 'Drywall', D(20));
  store.put('bidRequests', { ...store.get('bidRequests', elec.id), status: 'open' });
  store.put('bidRequests', { ...store.get('bidRequests', late.id), status: 'open', dueDate: D(-5) });
  store.put('bidRequests', { ...store.get('bidRequests', done.id), status: 'awarded' });
  store.put('invitations', { requestId: elec.id, buyerOrgId: gc.id, sellerOrgId: 'sub-1', intent: 'undecided' });
  store.put('submissions', { requestId: elec.id, sellerOrgId: 'sub-1', total: 1000 });
  const won = store.put('submissions', { requestId: done.id, sellerOrgId: 'sub-2', total: 900, status: 'awarded' });
  store.put('bidRequests', { ...store.get('bidRequests', done.id), awardedSubmissionId: won.id });
  pkg(draft.id, 'Framing', D(30));

  const pf = publisherPortfolio(store, gc, { at: Date.now() });
  assert.equal(pf.projects, 2);
  assert.equal(pf.openPackages, 2);
  assert.equal(pf.awardedPackages, 1);
  assert.equal(pf.bids, 2);
  const c = pf.rows.find(r => r.id === clinic.id);
  assert.equal(c.packages, 3);
  assert.equal(c.openPackages, 2);
  assert.equal(c.invitations, 1);
  assert.equal(c.city, 'Ankeny');
  assert.equal(c.nextBidDate, D(-5), 'the earliest open bid date is the next one');
  assert.ok(c.attention.some(a => /past the bid date/.test(a)), 'a package past its bid date is flagged');
  assert.ok(c.attention.some(a => /waiting for an award/.test(a)), 'a bid waiting on an award is flagged');
  const d = pf.rows.find(r => r.id === draft.id);
  assert.equal(d.status, 'draft');
  assert.ok(d.attention.includes('Not published yet'));
  assert.equal(c.budget.estimate, 48500000, 'the estimate is the value the owner entered');
  assert.equal(c.budget.awarded, 900, 'the awarded drywall package is counted at its signed amount');
  assert.equal(c.budget.awardedVsEstimate, 0, 'awarded work as a share of the estimate, to one decimal place');
  assert.equal(c.budget.lowestOpenBid, 1000, 'the lowest open bid is the electrical bid');
  assert.equal(d.budget.awarded, null, 'a project with nothing awarded shows no awarded amount');
  assert.equal(pf.awardedValue, 900);
  assert.equal(publisherPortfolio(store, other).projects, 0, 'another company sees none of these projects');
});
